// Copies the compiled contract's ABI and creation code into the site and computes its CREATE2
// address under the deterministic deployer. Run after `forge build` in contracts/.
import { readFileSync, writeFileSync } from "node:fs";
import { getContractAddress } from "viem";

const FACTORY = "0x4e59b44847b379578588920ca78fbf26c0b4956c";
const SALT = `0x${"00".repeat(32)}`;
const artifact = JSON.parse(readFileSync(new URL("../contracts/out/NumberSlideSessions.sol/NumberSlideSessions.json", import.meta.url), "utf8"));
const bytecode = artifact.bytecode.object;
const address = getContractAddress({ opcode: "CREATE2", from: FACTORY, salt: SALT, bytecode });
const out = `// Generated by scripts/export-contract.mjs from contracts/out. Do not edit by hand.
export const CREATE2_FACTORY = "${FACTORY}" as const;
export const CREATE2_SALT = "${SALT}" as const;
/** Where NumberSlideSessions lives on Sepolia: the CREATE2 address of this exact bytecode and salt. */
export const GAME_ADDRESS = "${address}" as const;
export const GAME_BYTECODE = "${bytecode}" as const;
export const GAME_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const;
`;
writeFileSync(new URL("../src/chain/contract.generated.ts", import.meta.url), out);
console.log(`NumberSlideSessions → ${address} (${(bytecode.length - 2) / 2} bytes of creation code)`);
